import turtle as t #подключаем модуль "черепаха"
t.left(90) #поворачивает черепаху на 90 градусов влево
t.screensize(10000, 10000) #масштаб
k = 30 #коэффициент увеличения
t.speed(50) #скорость черепахи
#построение фигуры
for i in range(4):
    t.forward(10*k)
    t.right(60)
    t.forward(10*k)
    t.right(120)
#поднимаем перо чтобы не рисовать линии
t.up()
t.speed(50)
#алгоритм построения точек
for x in range(-5, 20):
    for y in range(0, 20):
        t.goto(x*k, y*k)
        t.dot(6, "green") #рисует точки размером 5 красного цвета
t.done() #завершение программы
    
