import turtle
t = turtle.Pen()
t.color(1, 0, 0)
t.begin_fill() #начало заливки
t.fd(100)
t.lt(90)
t.fd(20)
t.lt(90)
t.fd(20)
t.rt(90)
t.fd(20)
t.lt(90)
t.fd(60)
t.lt(90)
t.fd(20)
t.rt(90)
t.fd(20)
t.lt(90)
t.fd(20)
t.end_fill() #конец заливки
#переднее колесо
t.color(0, 0, 0)
t.up()
t.fd(10)
t.down()
t.begin_fill()
t.circle(10)
t.end_fill()
#заднее колесо
t.setheading(0) #разворачивает черепашку в необходимом направлении
t.up()
t.fd(90)
t.rt(90)
t.fd(10)
t.setheading(0)
t.begin_fill()
t.down()
t.circle(10)
t.end_fill()
